#!/usr/bin/env python3
"""
SYNTHETIC DORA METRICS FOR HEALTHQUEUE
======================================
Every number this script produces is SYNTHETIC. It is generated from the
assumptions in SCENARIO below, using a fixed random seed. None of it was measured
from a real deployment or from production. It exists to demonstrate how the four
DORA metrics are calculated, compared with published benchmarks, and turned into
toil-reduction recommendations.

Usage (from the repo root):
    python dora/dora_synthetic.py            # default seed
    python dora/dora_synthetic.py --seed 7   # a different synthetic quarter

Outputs (in dora/output/, every file name and row is marked SYNTHETIC):
    deployments_SYNTHETIC.csv
    report_SYNTHETIC.md

Standard library only.
"""
import argparse
import csv
import math
import random
import statistics
from datetime import datetime, timedelta
from pathlib import Path

SEED = 365
WINDOW_DAYS = 90
# A hypothetical first quarter after launch (a Monday), clearly not real history.
START = datetime(2027, 1, 4)
END = START + timedelta(days=WINDOW_DAYS)
BUSINESS_START, BUSINESS_END = 9, 17  # humans act only in these hours, Monday to Friday

# --- Scenario assumptions (all invented; they describe a small team using the
# --- two-pull-request GitOps flow in this repository) -----------------------
SCENARIO = {
    "commits_per_weekday": 0.9,
    "pr_review_wait_median_min": 180,
    "manifest_bump_pr_median_min": 120,
    "ci_checks_mean_min": 7,
    "publish_image_mean_min": 6,
    "argocd_poll_wait_max_min": 3,
    "rollout_range_min": (2, 4),
    "failure_probability": 0.12,
    "failure_causes": {
        # cause: (weight, detection median minutes, caused by a hand-edited manifest?)
        "bad_image_tag": (0.35, 6, True),
        "manifest_config_error": (0.20, 10, True),
        "app_regression": (0.30, 45, False),
        "resource_limits": (0.15, 30, False),
    },
    "revert_open_pr_median_min": 10,
    "revert_expedited_review_median_min": 25,
    "revert_ci_mean_min": 5,
}

LEAD_STAGES = [
    # (column, label, kind)
    ("pr_review_wait", "Waiting for pull request review", "manual"),
    ("ci_checks", "CI: tests, build, scan", "automated"),
    ("publish_image", "Publish: push, SBOM, sign, attest", "automated"),
    ("manifest_bump_pr", "Second pull request to change the image tag", "manual"),
    ("off_hours_wait", "Waiting for nights and weekends", "queue"),
    ("argocd_sync_wait", "Argo CD polling delay", "automated"),
    ("rollout", "Pod rollout", "automated"),
]
RECOVERY_STAGES = [
    ("detect", "Detecting the failure", "detection"),
    ("open_revert_pr", "Opening the revert pull request", "manual"),
    ("expedited_review", "Waiting for expedited review", "manual"),
    ("recovery_ci", "CI on the revert", "automated"),
    ("recovery_sync", "Argo CD polling delay", "automated"),
    ("recovery_rollout", "Pod rollout", "automated"),
]

# DORA 2024 Accelerate State of DevOps Report, "Performance levels" (v2024.3).
BENCHMARKS = [
    # level, lead time, deployment frequency, change failure rate (typical), recovery
    ("Elite", "under 1 day", "on demand (multiple per day)", "5%", "under 1 hour"),
    ("High", "1 day to 1 week", "once a day to once a week", "20%", "under 1 day"),
    ("Medium", "1 week to 1 month", "once a week to once a month", "10%", "under 1 day"),
    ("Low", "1 to 6 months", "once a month to once every 6 months", "40%", "1 week to 1 month"),
]
CFR_TYPICAL = {"Elite": 5.0, "Medium": 10.0, "High": 20.0, "Low": 40.0}

BANNER = (
    "SYNTHETIC DATA. Generated by dora/dora_synthetic.py with seed {seed}. "
    "Not measured from production."
)


# ---------------------------------------------------------------- helpers ---
def lognormal(rng, median, sigma):
    return rng.lognormvariate(math.log(median), sigma)


def poisson(rng, lam):
    limit, k, p = math.exp(-lam), 0, 1.0
    while True:
        k += 1
        p *= rng.random()
        if p <= limit:
            return k - 1


def next_business_time(dt):
    """Move dt forward to the next moment inside Monday-Friday business hours."""
    while True:
        if dt.weekday() >= 5 or dt.hour >= BUSINESS_END:
            dt = (dt + timedelta(days=1)).replace(hour=BUSINESS_START, minute=0, second=0, microsecond=0)
            continue
        if dt.hour < BUSINESS_START:
            return dt.replace(hour=BUSINESS_START, minute=0, second=0, microsecond=0)
        return dt


def human_stage(rng, t, median, sigma=0.8):
    """A stage a person must do. Returns (finish time, working minutes, off-hours minutes)."""
    working = lognormal(rng, median, sigma)
    ready = t + timedelta(minutes=working)
    finish = next_business_time(ready)
    return finish, working, (finish - ready).total_seconds() / 60


def percentile(values, pct):
    data = sorted(values)
    if not data:
        return None
    pos = (len(data) - 1) * pct / 100
    low, high = math.floor(pos), math.ceil(pos)
    return data[low] + (data[high] - data[low]) * (pos - low)


def fmt_minutes(m):
    if m is None:
        return "n/a"
    if m < 90:
        return f"{m:.1f} min"
    if m < 2 * 1440:
        return f"{m / 60:.1f} h"
    return f"{m / 1440:.1f} days"


# ------------------------------------------------------------- generation ---
def simulate_change(rng, commit_time, idx):
    s = SCENARIO
    t = commit_time
    stages = {}

    t, stages["pr_review_wait"], off1 = human_stage(rng, t, s["pr_review_wait_median_min"], 0.9)
    stages["ci_checks"] = max(3.0, rng.gauss(s["ci_checks_mean_min"], 1.5))
    stages["publish_image"] = max(3.0, rng.gauss(s["publish_image_mean_min"], 1.5))
    t += timedelta(minutes=stages["ci_checks"] + stages["publish_image"])
    t, stages["manifest_bump_pr"], off2 = human_stage(rng, t, s["manifest_bump_pr_median_min"], 0.8)
    stages["off_hours_wait"] = off1 + off2
    stages["argocd_sync_wait"] = rng.uniform(0, s["argocd_poll_wait_max_min"])
    stages["rollout"] = rng.uniform(*s["rollout_range_min"])

    stages = {k: round(v, 2) for k, v in stages.items()}
    lead = round(sum(stages.values()), 2)
    row = {
        "id": f"D{idx:03d}",
        "data_source": "SYNTHETIC",
        "commit_time": commit_time.isoformat(timespec="minutes"),
        "deploy_time": (commit_time + timedelta(minutes=lead)).isoformat(timespec="minutes"),
        "lead_time_minutes": lead,
        **stages,
        "failed": False,
        "failure_cause": "",
        "manual_manifest_cause": "",
        **{key: "" for key, _, _ in RECOVERY_STAGES},
        "recovery_minutes": "",
    }

    if rng.random() < s["failure_probability"]:
        causes = list(s["failure_causes"])
        weights = [s["failure_causes"][c][0] for c in causes]
        cause = rng.choices(causes, weights)[0]
        _, detect_median, manual = s["failure_causes"][cause]
        rec = {
            "detect": lognormal(rng, detect_median, 0.6),
            "open_revert_pr": lognormal(rng, s["revert_open_pr_median_min"], 0.5),
            "expedited_review": lognormal(rng, s["revert_expedited_review_median_min"], 0.7),
            "recovery_ci": max(3.0, rng.gauss(s["revert_ci_mean_min"], 1.0)),
            "recovery_sync": rng.uniform(0, s["argocd_poll_wait_max_min"]),
            "recovery_rollout": rng.uniform(*s["rollout_range_min"]),
        }
        rec = {k: round(v, 2) for k, v in rec.items()}
        row.update(failed=True, failure_cause=cause, manual_manifest_cause=manual, **rec,
                   recovery_minutes=round(sum(rec.values()), 2))
    return row


def generate(seed=SEED):
    """Return (rows, censored). censored = changes that would deploy after the window."""
    rng = random.Random(seed)
    rows, censored = [], 0
    for d in range(WINDOW_DAYS):
        day = START + timedelta(days=d)
        if day.weekday() >= 5:
            continue
        for _ in range(poisson(rng, SCENARIO["commits_per_weekday"])):
            minute = rng.uniform(0, (BUSINESS_END - BUSINESS_START) * 60)
            commit = day.replace(hour=BUSINESS_START) + timedelta(minutes=minute)
            row = simulate_change(rng, commit, 0)
            if datetime.fromisoformat(row["deploy_time"]) >= END:
                censored += 1
            else:
                rows.append(row)
    rows.sort(key=lambda r: r["deploy_time"])
    for i, row in enumerate(rows, start=1):
        row["id"] = f"D{i:03d}"
    return rows, censored


# ------------------------------------------------------------ calculation ---
def compute_metrics(rows, window_days=WINDOW_DAYS):
    failed = [r for r in rows if r["failed"]]
    leads = [r["lead_time_minutes"] for r in rows]
    recov = [r["recovery_minutes"] for r in failed]
    return {
        "deployments": len(rows),
        "failed_deployments": len(failed),
        "deploys_per_day": len(rows) / window_days,
        "deploys_per_week": len(rows) / window_days * 7,
        "lead_median": statistics.median(leads) if leads else None,
        "lead_p90": percentile(leads, 90),
        "cfr_percent": len(failed) / len(rows) * 100 if rows else None,
        "recovery_median": statistics.median(recov) if recov else None,
        "recovery_mean": statistics.mean(recov) if recov else None,
    }


def classify_frequency(per_day):
    if per_day > 1:
        return "Elite"
    if per_day >= 1 / 7:
        return "High"
    if per_day >= 1 / 30:
        return "Medium"
    return "Low"


def classify_lead_time(minutes):
    if minutes < 1440:
        return "Elite"
    if minutes < 7 * 1440:
        return "High"
    if minutes < 30 * 1440:
        return "Medium"
    return "Low"


def classify_recovery(minutes):
    if minutes < 60:
        return "Elite"
    if minutes < 1440:
        return "High or Medium (DORA publishes the same band for both)"
    if minutes < 7 * 1440:
        return "Between High/Medium and Low"
    return "Low"


def classify_cfr(percent):
    """DORA publishes one typical value per level, and they are not in order
    (Medium 10% is lower than High 20%). Report the level whose typical value is nearest."""
    return min(CFR_TYPICAL, key=lambda level: (abs(CFR_TYPICAL[level] - percent), CFR_TYPICAL[level]))


def stage_stats(rows, stages, only_failed=False):
    data = [r for r in rows if r["failed"]] if only_failed else rows
    means = {col: statistics.mean(r[col] for r in data) for col, _, _ in stages} if data else {}
    total = sum(means.values()) or 1
    return [(col, label, kind, means[col], means[col] / total * 100) for col, label, kind in stages]


def cause_stats(rows):
    failed = [r for r in rows if r["failed"]]
    total_recovery = sum(r["recovery_minutes"] for r in failed) or 1
    out = []
    for cause in SCENARIO["failure_causes"]:
        group = [r for r in failed if r["failure_cause"] == cause]
        if group:
            minutes = sum(r["recovery_minutes"] for r in group)
            out.append((cause, len(group), minutes / len(group), minutes / total_recovery * 100,
                        SCENARIO["failure_causes"][cause][2]))
    return sorted(out, key=lambda x: -x[1])


# -------------------------------------------------------- recommendations ---
CAUSE_FIXES = {
    "bad_image_tag": "Add a CI check that the image tag in k8s/deployment.yaml exists in the registry "
                     "(or deploy by digest), so a mistyped tag fails the pull request instead of production.",
    "manifest_config_error": "Validate Kubernetes manifests in CI (schema validation and a server-side "
                             "dry run) so configuration mistakes fail before merge.",
    "app_regression": "Use a progressive rollout and alert on SLO burn rate (observability/alerts.yml) so "
                      "a bad release is caught and rolled back early.",
    "resource_limits": "Load-test before release and right-size CPU and memory limits in k8s/deployment.yaml.",
}


def recommendations(rows, metrics):
    recs = []
    ls = {col: (mean, share) for col, _, _, mean, share in stage_stats(rows, LEAD_STAGES)}
    failed = [r for r in rows if r["failed"]]
    n = len(rows)

    # 1. The mechanical second pull request.
    mean_b, share_b = ls["manifest_bump_pr"]
    hand_edited = sum(1 for r in failed if r["manual_manifest_cause"] is True)
    est_leads = [max(r["lead_time_minutes"] - r["manifest_bump_pr"] + 5, 0) for r in rows]
    recs.append((
        mean_b * n,
        "Automate the image-tag pull request",
        f"Every one of the {n} deployments needed a second, mechanical pull request to change the image tag. "
        f"That stage averaged {fmt_minutes(mean_b)} ({share_b:.0f}% of lead time), and {hand_edited} of "
        f"{len(failed)} failed deployments came from a hand-edited manifest. Have CI open the tag-change "
        f"pull request after publish (or use an image-update tool) and keep the human review. Rough estimate: "
        f"median lead time would fall from {fmt_minutes(metrics['lead_median'])} to about "
        f"{fmt_minutes(statistics.median(est_leads))} (this ignores re-queuing to business hours).",
    ))

    # 2. Review wait.
    mean_r, share_r = ls["pr_review_wait"]
    recs.append((
        mean_r * n,
        "Shorten the wait for pull request review",
        f"Waiting for review averaged {fmt_minutes(mean_r)} per change ({share_r:.0f}% of lead time). "
        f"Keep pull requests small, agree a review turnaround target, and rotate a named reviewer.",
    ))

    # 3. The most common failure cause.
    causes = cause_stats(rows)
    if causes:
        cause, count, mean_rec, _, _ = causes[0]
        recs.append((
            count * mean_rec,
            f"Prevent the most common failure: {cause.replace('_', ' ')}",
            f"{count} of {len(failed)} failed deployments ({count / len(failed) * 100:.0f}%) had this cause, "
            f"with an average recovery of {fmt_minutes(mean_rec)}. {CAUSE_FIXES[cause]}",
        ))

    # 4. Recovery: human steps versus detection.
    if failed:
        rs = {col: share for col, _, _, _, share in stage_stats(rows, RECOVERY_STAGES, only_failed=True)}
        human = rs["open_revert_pr"] + rs["expedited_review"]
        total_recovery = sum(r["recovery_minutes"] for r in failed)
        recs.append((
            human / 100 * total_recovery,
            "Make rollback a pre-approved fast path",
            f"{human:.0f}% of recovery time was people opening and approving the revert pull request, and "
            f"{rs['detect']:.0f}% was detecting the failure. Median recovery was "
            f"{fmt_minutes(metrics['recovery_median'])}. Consider letting a revert of the last deployment merge on green "
            f"checks without a second approver (a change-control decision for leadership), and deploy the SLO "
            f"burn-rate alerts to shorten detection.",
        ))

    return [(title, text) for _, title, text in sorted(recs, key=lambda r: -r[0])]


# ----------------------------------------------------------------- output ---
def write_outputs(rows, censored, seed, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    csv_path = out_dir / "deployments_SYNTHETIC.csv"
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    m = compute_metrics(rows)
    banner = BANNER.format(seed=seed)
    tiers = {
        "freq": classify_frequency(m["deploys_per_day"]),
        "lead": classify_lead_time(m["lead_median"]),
        "cfr": classify_cfr(m["cfr_percent"]),
        "rec": classify_recovery(m["recovery_median"]) if m["recovery_median"] is not None else "n/a",
    }

    lines = [
        f"# DORA Metrics Report (SYNTHETIC)", "",
        f"> **{banner}**", ">",
        "> These figures describe an invented scenario for a hypothetical first quarter after launch. "
        "They must not be read, quoted, or presented as HealthQueue's real delivery performance.", "",
        "## What this is", "",
        f"A reproducible demonstration of how the four DORA metrics are calculated and compared with "
        f"published benchmarks. The script simulates {WINDOW_DAYS} days "
        f"({START:%Y-%m-%d} to {(END - timedelta(days=1)):%Y-%m-%d}) of deployments through this repository's "
        f"two-pull-request GitOps pipeline, using the assumptions listed below. "
        f"Re-run with `python dora/dora_synthetic.py --seed {seed}` to get identical output.", "",
        "## Results (synthetic)", "",
        "| Metric | Synthetic result | Closest DORA level | Basis |", "|---|---|---|---|",
        f"| Deployment frequency | {m['deployments']} deployments, {m['deploys_per_week']:.1f} per week | "
        f"**{tiers['freq']}** | Deployments per calendar day over {WINDOW_DAYS} days |",
        f"| Lead time for changes | median {fmt_minutes(m['lead_median'])}, 90th percentile "
        f"{fmt_minutes(m['lead_p90'])} | **{tiers['lead']}** | Median, commit to running in the cluster |",
        f"| Change failure rate | {m['cfr_percent']:.1f}% ({m['failed_deployments']} of {m['deployments']}) | "
        f"**{tiers['cfr']}** | Nearest published typical value (see note) |",
        f"| Failed deployment recovery time | median {fmt_minutes(m['recovery_median'])}, "
        f"mean {fmt_minutes(m['recovery_mean'])} | **{tiers['rec']}** | Median, failed deploy to service restored |",
        "",
        "*Change failure rate note:* DORA publishes one typical value per level and they are not in order "
        "(Medium, 10%, is lower than High, 20%), so the result is matched to the nearest typical value instead "
        "of a threshold.", "",
        "## DORA benchmarks used", "",
        "Source: DORA, *Accelerate State of DevOps Report 2024*, \"Performance levels\" (v2024.3), the most "
        "recent four-level table. Check these values against the report on dora.dev before citing them.", "",
        "| Level | Lead time | Deployment frequency | Change failure rate (typical) | Failed deployment recovery |",
        "|---|---|---|---|---|",
        *[f"| {a} | {b} | {c} | {d} | {e} |" for a, b, c, d, e in BENCHMARKS], "",
        "## Where lead time goes (synthetic)", "",
        "| Stage | Kind | Mean | Share of lead time |", "|---|---|---|---|",
        *[f"| {label} | {kind} | {fmt_minutes(mean)} | {share:.0f}% |"
          for _, label, kind, mean, share in stage_stats(rows, LEAD_STAGES)], "",
        "*Reading this table:* \"Waiting for nights and weekends\" is calendar time when nobody is working. "
        "It is not toil and nobody can remove it by automating a step, but it explains why lead time is "
        "measured in hours, not minutes. Its size comes from the simplified business-hours model, so the "
        "other percentages are shares of a total that includes it.", "",
        "## Failures (synthetic)", "",
        "| Cause | Count | Mean recovery | Share of all recovery time | Hand-edited manifest? |",
        "|---|---|---|---|---|",
        *[f"| {c.replace('_', ' ')} | {n} | {fmt_minutes(mean)} | {share:.0f}% | {'yes' if manual else 'no'} |"
          for c, n, mean, share, manual in cause_stats(rows)], "",
        "## Toil-reduction recommendations", "",
        "Each recommendation cites a number from the synthetic results above, ranked by the total elapsed "
        "minutes it involves across the quarter. Because the data is invented, they demonstrate the method. With real data the same "
        "script logic would rank real bottlenecks.", "",
    ]
    for i, (title, text) in enumerate(recommendations(rows, m), start=1):
        lines += [f"{i}. **{title}.** {text}", ""]

    lines += [
        "## Scenario assumptions (all invented)", "",
        f"- About {SCENARIO['commits_per_weekday']} changes started per weekday; people act only Monday to "
        f"Friday, {BUSINESS_START}:00 to {BUSINESS_END}:00.",
        f"- Median wait for pull request review: {SCENARIO['pr_review_wait_median_min']} min. "
        f"Median time for the second (image-tag) pull request: {SCENARIO['manifest_bump_pr_median_min']} min.",
        f"- {SCENARIO['failure_probability'] * 100:.0f}% of deployments fail, split across four causes; "
        f"recovery is a revert pull request with expedited review.",
        (f"- {censored} change(s) started late in the window and would deploy after it; they are excluded."
         if censored else "- No changes were excluded for deploying after the window."), "",
        "## Limitations", "",
        "- The results follow from the assumptions above and say nothing about real performance.",
        "- Lead time uses elapsed time and a simplified business-hours model.",
        (f"- Only {m['failed_deployments']} failed deployments occurred, so the change failure rate and recovery "
         f"results are fragile: one more or one fewer failure could move them across a level boundary "
         f"(median recovery {fmt_minutes(m['recovery_median'])} against a 60-minute Elite cutoff)."
         if m["failed_deployments"] < 20 else
         "- Failure counts are large enough for the percentages to be reasonably stable."),
        "- Deployment rework rate, DORA's fifth metric, is not modeled.",
        "- Real measurement would take deployment events from Git and GitHub Actions, and failures from "
        "incident records.", "",
        f"**{banner}**", "",
    ]
    report_path = out_dir / "report_SYNTHETIC.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    return csv_path, report_path, m, tiers


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--seed", type=int, default=SEED)
    args = parser.parse_args()

    rows, censored = generate(args.seed)
    out_dir = Path(__file__).resolve().parent / "output"
    csv_path, report_path, m, tiers = write_outputs(rows, censored, args.seed, out_dir)

    print("=" * 72)
    print(BANNER.format(seed=args.seed))
    print("=" * 72)
    print(f"Deployments: {m['deployments']} ({m['deploys_per_week']:.1f}/week)  -> {tiers['freq']}")
    print(f"Lead time (median): {fmt_minutes(m['lead_median'])}  -> {tiers['lead']}")
    print(f"Change failure rate: {m['cfr_percent']:.1f}%  -> closest to {tiers['cfr']}")
    print(f"Recovery (median): {fmt_minutes(m['recovery_median'])}  -> {tiers['rec']}")
    print(f"Wrote {csv_path}")
    print(f"Wrote {report_path}")


if __name__ == "__main__":
    main()
